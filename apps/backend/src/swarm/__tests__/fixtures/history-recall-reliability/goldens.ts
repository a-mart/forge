import { ACTOR, ENTRY, NEEDLE, SESSION } from "./ids.js";

export type GateKind = "quality" | "readiness" | "integrity" | "resources";
export type BaselineExpectation =
  | "pass"
  | "miss"
  | "wrong-rank"
  | "incomplete-projection"
  | "clipped"
  | "unstable-page"
  | "coverage-lie"
  | "missing-api"
  | "wrong-identity";
export type CorpusLane = "compact" | "giant" | "scale" | "lifecycle";
export type SearchOrder = "relevance" | "newest";

export interface ExpectedRef {
  sessionAgentId: string;
  actorAgentId: string;
  entryId: string;
  partId?: string;
  kind?: "message" | "tool_call" | "tool_result" | "checkpoint";
  textIncludes?: string[];
}

export interface GoldenCase {
  id: string;
  category: string;
  gate: GateKind;
  lane: CorpusLane;
  critical: boolean;
  summary: string;
  callerAgentId: string;
  op: "search" | "read" | "sessions" | "lifecycle";
  query?: string;
  scope?: "session" | "project" | "all_local";
  sessionAgentId?: string;
  profileId?: string;
  reason?: string;
  order?: SearchOrder;
  window?: "all" | "current" | "previous";
  kinds?: Array<"message" | "tool_call" | "tool_result" | "checkpoint">;
  toolName?: string;
  includeHistoryArtifacts?: boolean;
  limit?: number;
  since?: string;
  until?: string;
  /** Authored decisive refs. Never copied from an engine top-hit dump. */
  expectedRefs: ExpectedRef[];
  requireAllExpectedInTop?: number;
  newestFirst?: string[];
  forbiddenEntryIds?: string[];
  forbiddenText?: string[];
  expectedComplete?: boolean;
  coverage?: "ready" | "building" | "degraded" | "unavailable" | "unknown";
  expectErrorIncludes?: string;
  expectedBaseline: BaselineExpectation;
  baselineNote: string;
}

