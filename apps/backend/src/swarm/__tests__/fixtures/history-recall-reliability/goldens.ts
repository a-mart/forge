export function goldensForLane(lane: CorpusLane | "all"): GoldenCase[] {
  if (lane === "all") {
    return GOLDENS;
  }
  if (lane === "compact") {
    return GOLDENS.filter((entry) => entry.lane === "compact" || entry.lane === "lifecycle");
  }
  return GOLDENS.filter((entry) => entry.lane === lane || entry.lane === "compact" || entry.lane === "lifecycle");
}

export function qualityCases(): GoldenCase[] {
  return GOLDENS.filter((entry) => entry.gate === "quality" && entry.lane === "compact");
}
